struct tile
{
    SDL_Rect tileRect;
    int isActive;
    int selectedTile;
};

struct map
{
    SDL_Renderer *pRenderer;
    SDL_Texture *pTexture;
    SDL_Rect rect;
    Tile tileMap[AMOUNT_OF_TILES_HORIZONTAL][AMOUNT_OF_TILES_VERTICAL];
};

Map *createMap(SDL_Renderer *pRenderer, int window_width, int window_height)
{
    Map *map = malloc(sizeof(Map));
    if(!map) return NULL;

    map->pRenderer = pRenderer;

    SDL_Surface *surface = IMG_Load("Resources/Sprite-dirt.png");
    if (!surface) {
        printf("Error loading foundation.png: %s\n", IMG_GetError());
        free(map);
        return NULL;
    }

    map->pTexture = SDL_CreateTextureFromSurface(pRenderer, surface);
    SDL_FreeSurface(surface);

    if (!map->pTexture) {
        printf("Error creating platform texture: %s\n", SDL_GetError());
        free(map);
        return NULL;
    }

    for (int x = 0; x < AMOUNT_OF_TILES_HORIZONTAL; x++) 
    {
        for (int y = 0; y < AMOUNT_OF_TILES_VERTICAL; y++) 
        {
            map->tileMap[x][y] = createTile(x*TILESIZE_PIXELS, y*TILESIZE_PIXELS, mapTemplate2[x][y]);
        }
    }
    return map;
}

void drawTiles(Map *tiles)
{
    for (int x = 0; x < AMOUNT_OF_TILES_HORIZONTAL; x++)
    {
        for(int y = 0; y < AMOUNT_OF_TILES_VERTICAL; y++)
        {
            SDL_Rect selectedTexture = getSelectedTile(tiles->tileMap[x][y].selectedTile);
            if (!tiles->tileMap[x][y].isActive) continue;
            SDL_RenderCopy(tiles->pRenderer, tiles->pTexture, &selectedTexture, &tiles->tileMap[x][y].tileRect);
        }
    }
}

SDL_Rect getSelectedTile(int tileNr)
{
    SDL_Rect selectedTexture;
    selectedTexture.x = (tileNr % 6)*64;
    selectedTexture.y = (tileNr / 6)*64;
    selectedTexture.w = 64;
    selectedTexture.h = 64;
    return selectedTexture;
}

SDL_Rect getTileRect(Map *tiles, int x, int y)
{
    return tiles->tileMap[x][y].tileRect;
}

int isTileAktive(Map *tiles, int x, int y)
{
    return tiles->tileMap[x][y].isActive;
}

void inactivateTile(Map *tiles, int x, int y)
{
    tiles->tileMap[x][y].isActive = 0;
}

void destroyTiles(Map *tiles, int tilecount)
{
    if (!tiles) return;

    if (tilecount > 0 && tiles[0].pTexture) {
        SDL_DestroyTexture(tiles[0].pTexture);
    }

    free(tiles);
}

Tile createTile(int x, int y, int selectedTile)
{
    Tile tile;

    tile.tileRect.x = x;
    tile.tileRect.y = y;
    tile.tileRect.h = TILESIZE_PIXELS;
    tile.tileRect.w = TILESIZE_PIXELS;
    tile.selectedTile = selectedTile;
    if (selectedTile == -1)
    {
        tile.isActive = 0;
    }
    else tile.isActive = 1;
    return tile;
}